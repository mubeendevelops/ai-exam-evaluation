"""api/schemas/papers.py — Pydantic v2 models for paper generation.

The response models below mirror the dict `core/paper_generator.generate_paper`
already returns, field for field, rather than flattening it. That structure —
sections, each with top-level slots, each with the leaf slots that actually
carry a question — IS the paper: a flat list of questions would lose which
either/or section they belong to and how many of a section a student must
answer, which is precisely what makes a paper a paper rather than a quiz.

`warnings` is part of the success response, not an error channel. A paper with
an unfilled OPTIONAL slot is valid but degraded, and the caller has to be told
which slot so someone can write the missing question. An unfilled MANDATORY
slot is not a warning at all — generate_paper raises, and the endpoint answers
409 with no paper persisted.

`warnings` carries STRUCTURED `SlotWarning` objects (slot_label, section,
marks, reason) — not prose strings. Before this pass, an unfilled optional
slot was a real hole in the paper buried inside a formatted sentence in a
plain `list[str]`, which forced a client to parse English to find out which
slot, in which section, at how many marks, was missing. `is_complete` and
`filled_marks`/`pattern_total_marks` make the same fact visible WITHOUT
reading `warnings` at all — a client that only checks `is_complete` still
learns the paper has a hole, and one that only compares `filled_marks` to
`pattern_total_marks` learns how big it is, in marks rather than slot count.
"""
from __future__ import annotations

import datetime as dt
import uuid
from typing import Any, Literal

from pydantic import BaseModel, ConfigDict, Field

#: paper_status enum (migration 008). A generated paper starts as 'draft' —
#: generation fills slots, it does not publish a paper.
PaperStatus = Literal["draft", "finalized"]


class PaperSummary(BaseModel):
    """One row of GET /api/v1/papers.

    No college_id here either, for the identical reason
    api/schemas/questions.py's header gives: generated_papers has no such
    column (migration 008 line 15 — shared, no RLS), so a college_id field
    would be a fabrication a future endpoint could be tempted to filter on.
    """

    model_config = ConfigDict(extra="forbid")

    paper_id: uuid.UUID
    pattern_id: uuid.UUID
    name: str
    status: PaperStatus
    generated_at: dt.datetime
    generated_by: uuid.UUID | None = Field(
        default=None, description="NULL = system-generated.",
    )


def paper_to_summary(row: dict[str, Any]) -> PaperSummary:
    return PaperSummary(
        paper_id=row["paper_id"], pattern_id=row["pattern_id"], name=row["name"],
        status=row["status"], generated_at=row["generated_at"],
        generated_by=row["generated_by"],
    )


class PaperGenerateRequest(BaseModel):
    """POST /api/v1/papers/generate."""

    model_config = ConfigDict(extra="forbid")

    pattern_id: uuid.UUID = Field(
        description="The paper_pattern to fill. Must be is_active — generating "
                    "from a retired pattern is refused."
    )
    name: str = Field(
        min_length=1, max_length=500,
        description='Human-readable paper name, e.g. "AIML CIA-2 Aug 2026".',
    )
    # NO `generated_by`. It was an optional reviewer_id here, defaulting to
    # NULL ("system-generated", migration 008 line 62), and it was the same
    # hazard RE-4 removed from the review endpoints: a client could stamp any
    # reviewer's name on a paper it generated. generated_papers.generated_by
    # is now the authenticated caller's reviewer_id, always. The NULL branch
    # stays meaningful in the SCHEMA — the CLI and future system jobs still
    # write papers nobody generated by hand — but an HTTP request always has a
    # human behind it, so it never takes that branch.
    choose_count: int = Field(
        default=1, ge=1,
        description="Default choose_count for OPTIONAL sections — how many of "
                    "the section's questions a student must answer. Mandatory "
                    "sections ignore it and always use their full slot count.",
    )
    marks_tolerance: float = Field(
        default=1.0, ge=0.0, le=5.0,
        description="How far a question's marks_max may sit from the slot's "
                    "marks when no exact match exists. 0 disables fuzzy "
                    "matching, making generation exact-or-fail.",
    )


class AssignedSlot(BaseModel):
    """One LEAF slot: the level at which a question is actually assigned.

    `assigned` false with a null question_id is a real, expected state for an
    optional section — the slot exists in the pattern and the bank had nothing
    that fits. It is reported rather than silently dropped, because a caller
    rendering the paper needs to show the gap to whoever must fill it.
    """

    model_config = ConfigDict(extra="forbid")

    slot_id: uuid.UUID
    slot_label: str
    marks: float
    style: str
    assigned: bool
    question_id: uuid.UUID | None = None
    question_content: str | None = None
    question_marks: float | None = Field(
        default=None,
        description="The assigned question's own marks_max. Differs from "
                    "`marks` when it was matched within marks_tolerance rather "
                    "than exactly — that difference is the caller's to notice.",
    )


class PaperSlot(BaseModel):
    """A top-level slot. Parent slots (Q2 = Q2a + Q2b) are STRUCTURAL and
    carry no question of their own — only their leaves do, which is why
    `leaves` exists even for a standalone slot (it holds exactly itself)."""

    model_config = ConfigDict(extra="forbid")

    slot_label: str
    marks: float
    style: str
    is_parent: bool
    leaves: list[AssignedSlot]


class PaperSection(BaseModel):
    model_config = ConfigDict(extra="forbid")

    section_label: str
    section_order: int
    is_mandatory: bool
    choose_count: int
    slots: list[PaperSlot]


class SlotWarning(BaseModel):
    """One unfilled OPTIONAL slot, structured rather than a formatted
    sentence — a client renders "Q3 (Part B, 5M): <reason>" itself, or filters
    by section, or counts gaps per section, none of which a prose string
    supports without parsing it back apart.
    """

    model_config = ConfigDict(extra="forbid")

    slot_label: str
    section: str = Field(description="The section's label, e.g. 'Part B'.")
    marks: float
    reason: str = Field(
        description="Why no live question was assigned — today, always "
                    "'no matching live question' with the style/marks it "
                    "looked for; kept as text rather than an enum because "
                    "core/paper_generator.py's matching strategy (exact, "
                    "then ±marks_tolerance) may grow more failure shapes.",
    )


class PaperGenerateResponse(BaseModel):
    """The generated paper, as persisted."""

    model_config = ConfigDict(extra="forbid")

    paper_id: uuid.UUID
    pattern_id: uuid.UUID
    pattern_name: str
    name: str
    status: PaperStatus
    total_filled: int = Field(ge=0)
    total_slots: int = Field(ge=0)
    is_complete: bool = Field(
        description="False iff `warnings` is non-empty — every LEAF slot in "
                    "the pattern got a question. Equivalent to `not warnings`, "
                    "surfaced as its own field so a client can check "
                    "completeness without inspecting the warnings list.",
    )
    filled_marks: float = Field(
        ge=0,
        description="Sum of the MARKS of every filled slot (the slot's own "
                    "marks value, not the assigned question's marks_max, "
                    "which can differ slightly under marks_tolerance fuzzy "
                    "matching). Compare against `pattern_total_marks` to see "
                    "how much of the paper's intended marks are covered.",
    )
    pattern_total_marks: float = Field(
        ge=0,
        description="paper_patterns.total_marks for the pattern this paper "
                    "was generated from — the full marks the pattern is "
                    "worth when every slot is filled.",
    )
    sections: list[PaperSection]
    warnings: list[SlotWarning] = Field(
        default_factory=list,
        description="One entry per unfilled OPTIONAL slot. A paper with "
                    "warnings is valid but incomplete (is_complete=false); "
                    "unfilled MANDATORY slots are a 409, not a warning — see "
                    "this module's header.",
    )


def paper_to_response(result: dict[str, Any]) -> PaperGenerateResponse:
    """core/paper_generator.generate_paper's dict -> response model.

    A straight construction, not a rewrite: pydantic coerces the module's
    str-typed uuids into UUID objects and validates the shape, which is the
    only checking this mapping does. If generate_paper's return shape changes,
    this raises at the boundary instead of shipping a half-populated paper.
    """
    return PaperGenerateResponse(**result)
