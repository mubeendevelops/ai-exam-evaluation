"""Fine-tuning the detector (``tarn diagram train``) within 4 GB of VRAM.

RT-DETR R18 from ``PekingU/rtdetr_r18vd_coco_o365`` with a new 7-class head; fp32 (the GTX 1650
has no tensor cores: fp16 is slower there, D77), images letterboxed to ``size`` (1024: 2.5 GB
at batch 2, measured), gradient accumulation for a larger effective batch, AdamW with a lower
rate for the backbone, cosine schedule with warm-up, gradient clipping at 0.1 (as RT-DETR).

Sources are mixed by weight, not by size (the 7,000 Flowchart 3b images would drown the 600 FC
ones): each epoch draws ``steps × batch`` training images with replacement. FC skeleton images
have 1-pixel strokes: they are thickened before scaling so they survive it. Training
augmentations: horizontal flip, contrast/brightness, ink tint, noise, blur, scale jitter.

A checkpoint after every epoch (``checkpoint.pt``) lets a stopped run resume; the epoch with
the lowest validation loss is saved with ``save_pretrained`` plus ``tarn-detector.json``
(classes, size, sources, base model and licences, epochs, losses, weights hash)."""

import hashlib
import json
import math
import random
import time
from collections.abc import Callable, Sequence
from concurrent.futures import ThreadPoolExecutor
from dataclasses import asdict, dataclass, field
from pathlib import Path
from typing import Any

import cv2
import numpy as np

from tarn_adapters.diagram.dataset import CLASSES, Sample, image_path, read_manifest
from tarn_adapters.diagram.detector import MANIFEST, letterbox

BASE_MODEL = "PekingU/rtdetr_r18vd_coco_o365"
DEFAULT_WEIGHTS = {"fc_skeleton": 0.2, "fc_scan": 0.25, "fc3b": 0.25, "synthetic": 0.3}
LICENCES = {
    "model": "RT-DETR (transformers, Apache-2.0); base weights PekingU/rtdetr_r18vd_coco_o365 "
    "(Apache-2.0)",
    "fc_skeleton": "FC database offline 1.0 (Bresler, Prusa, Hlavac; CTU Prague): free to "
    "download, cite the authors; used to train a production model by the user's decision "
    "(D100)",
    "fc_scan": "as fc_skeleton",
    "fc3b": "Flowchart 3b (ISC UPIIZ students, Kaggle davbetm/flowchart-3b; licence 'Unknown' "
    "on Kaggle, the authors' code is MIT): used by the user's decision (D100)",
    "synthetic": "generated by Tarn (tarn diagram data synth)",
}


@dataclass
class TrainConfig:
    manifests: list[Path]
    out: Path
    base: str = BASE_MODEL
    size: int = 1024
    batch: int = 2
    accumulate: int = 4
    epochs: int = 12
    steps: int = 600
    """Optimiser steps × accumulate × batch = images per epoch."""
    lr: float = 1e-4
    backbone_lr: float = 1e-5
    warmup: int = 200
    seed: int = 14
    weights: dict[str, float] = field(default_factory=lambda: dict(DEFAULT_WEIGHTS))
    version: str = "1"
    val_limit: int = 300
    cache_dir: Path | None = None
    amp: bool = False
    """fp16 autocast with loss scaling: for GPUs with tensor cores (Colab's T4), not the
    GTX 1650 (D77)."""
    workers: int = 4
    """Threads that read and augment images while the GPU works (OpenCV frees the GIL)."""


def load_samples(manifests: Sequence[Path]) -> list[tuple[Path, Sample]]:
    return [(m, s) for m in manifests for s in read_manifest(m)]


def read_image(manifest: Path, sample: Sample) -> np.ndarray:
    image = cv2.imread(str(image_path(manifest, sample)), cv2.IMREAD_COLOR)
    if image is None:
        raise ValueError(f"cannot read {sample.image}")
    prepared = bool(sample.extra.get("prepared"))  # already thickened and scaled by `pack`
    if sample.source == "fc_skeleton" and not prepared:  # 1-pixel strokes: thicken them
        gray = cv2.cvtColor(image, cv2.COLOR_BGR2GRAY)
        ink = cv2.dilate(255 - gray, np.ones((3, 3), np.uint8), iterations=3)
        image = cv2.cvtColor(255 - ink, cv2.COLOR_GRAY2BGR)
    return image


def augment(
    image: np.ndarray,
    boxes: list[list[float]],
    rng: random.Random,
) -> tuple[np.ndarray, list[list[float]]]:
    h, w = image.shape[:2]
    if rng.random() < 0.5:
        image = image[:, ::-1].copy()
        boxes = [[w - b[2], b[1], w - b[0], b[3]] for b in boxes]
    out = image.astype(np.float32)
    out = out * rng.uniform(0.75, 1.2) + rng.uniform(-25, 25)
    if rng.random() < 0.4:  # ink tint (blue pen)
        dark = out.mean(axis=2, keepdims=True) < 128
        out = np.where(dark, out * np.array([1.4, 0.8, 0.6], np.float32), out)
    if rng.random() < 0.4:
        out += np.random.default_rng(rng.randrange(1 << 30)).normal(
            0, rng.uniform(2, 10), out.shape
        )
    image = np.clip(out, 0, 255).astype(np.uint8)
    if rng.random() < 0.3:
        image = cv2.GaussianBlur(image, (3, 3), rng.uniform(0.3, 1.2))
    if rng.random() < 0.5:  # scale jitter: shrink into a white canvas of the same size
        f = rng.uniform(0.6, 1.0)
        small = cv2.resize(
            image, (max(1, int(w * f)), max(1, int(h * f))), interpolation=cv2.INTER_AREA
        )
        canvas = np.full_like(image, 255)
        ox, oy = rng.randint(0, w - small.shape[1]), rng.randint(0, h - small.shape[0])
        canvas[oy : oy + small.shape[0], ox : ox + small.shape[1]] = small
        image = canvas
        boxes = [[b[0] * f + ox, b[1] * f + oy, b[2] * f + ox, b[3] * f + oy] for b in boxes]
    return image, boxes


def target(sample: Sample, boxes: list[list[float]], scale: float, size: int) -> dict[str, Any]:
    import torch

    labels, norm = [], []
    for obj, b in zip(sample.objects, boxes, strict=True):
        x0, y0, x1, y1 = (v * scale / size for v in b)
        x0, y0, x1, y1 = max(0.0, x0), max(0.0, y0), min(1.0, x1), min(1.0, y1)
        if x1 - x0 < 1e-4 or y1 - y0 < 1e-4:
            continue
        labels.append(CLASSES.index(obj.cls))
        norm.append([(x0 + x1) / 2, (y0 + y1) / 2, x1 - x0, y1 - y0])
    return {
        "class_labels": torch.tensor(labels, dtype=torch.long),
        "boxes": torch.tensor(norm, dtype=torch.float32).reshape(-1, 4),
    }


def content_box(sample: Sample, margin: float) -> tuple[int, int, int, int]:
    """The drawing's extent (every object) widened by ``margin`` of its size, in the image:
    the FC pages are mostly empty paper, while the pipeline hands the detector the diagram
    region of a page."""
    x0 = min(o.box[0] for o in sample.objects)
    y0 = min(o.box[1] for o in sample.objects)
    x1 = max(o.box[2] for o in sample.objects)
    y1 = max(o.box[3] for o in sample.objects)
    mx, my = (x1 - x0) * margin + 10, (y1 - y0) * margin + 10
    return (
        max(0, int(x0 - mx)),
        max(0, int(y0 - my)),
        min(sample.width, int(x1 + mx)),
        min(sample.height, int(y1 + my)),
    )


def cropped(sample: Sample) -> bool:
    return sample.source.startswith("fc_") and bool(sample.objects)


def example(
    manifest: Path, sample: Sample, size: int, rng: random.Random | None
) -> tuple[np.ndarray, dict[str, Any]]:
    image = read_image(manifest, sample)
    boxes = [list(o.box) for o in sample.objects]
    if cropped(sample):
        margin = 0.08 if rng is None else rng.uniform(0.02, 0.2)
        x0, y0, x1, y1 = content_box(sample, margin)
        image = image[y0:y1, x0:x1]
        boxes = [[b[0] - x0, b[1] - y0, b[2] - x0, b[3] - y0] for b in boxes]
    if rng is not None:
        image, boxes = augment(image, boxes, rng)
    pixels, scale = letterbox(image, size)
    return pixels, target(sample, boxes, scale, size)


def train(cfg: TrainConfig, log: Callable[[str], None] = print) -> Path:
    import torch
    from transformers import RTDetrForObjectDetection

    rng = random.Random(cfg.seed)  # noqa: S311  (sampling, not secrets)
    torch.manual_seed(cfg.seed)
    samples = load_samples(cfg.manifests)
    train_set = [x for x in samples if x[1].split == "train" and x[1].source in cfg.weights]
    val_set = [x for x in samples if x[1].split == "val"]
    rng.shuffle(val_set)
    val_set = val_set[: cfg.val_limit]
    if not train_set:
        raise ValueError("no training images: run `tarn diagram data prepare` / `synth` first")
    by_source: dict[str, list[tuple[Path, Sample]]] = {}
    for item in train_set:
        by_source.setdefault(item[1].source, []).append(item)
    present = {k: v for k, v in cfg.weights.items() if k in by_source}
    total = sum(present.values())
    mix = {k: v / total for k, v in present.items()}
    log(f"training images per source: { {k: len(v) for k, v in by_source.items()} }; mix {mix}")

    device = "cuda" if torch.cuda.is_available() else "cpu"
    cfg.out.mkdir(parents=True, exist_ok=True)
    checkpoint = cfg.out / "checkpoint.pt"
    model = RTDetrForObjectDetection.from_pretrained(
        cfg.base,
        num_labels=len(CLASSES),
        id2label=dict(enumerate(CLASSES)),
        label2id={c: i for i, c in enumerate(CLASSES)},
        ignore_mismatched_sizes=True,
        cache_dir=None if cfg.cache_dir is None else str(cfg.cache_dir),
    ).to(device)
    backbone = [p for n, p in model.named_parameters() if "backbone" in n]
    rest = [p for n, p in model.named_parameters() if "backbone" not in n]
    optimiser = torch.optim.AdamW(
        [{"params": backbone, "lr": cfg.backbone_lr}, {"params": rest, "lr": cfg.lr}],
        weight_decay=1e-4,
    )
    total_steps = cfg.epochs * cfg.steps

    def factor(step: int) -> float:
        if step < cfg.warmup:
            return (step + 1) / cfg.warmup
        progress = (step - cfg.warmup) / max(1, total_steps - cfg.warmup)
        return 0.05 + 0.95 * 0.5 * (1 + math.cos(math.pi * min(1.0, progress)))

    scheduler = torch.optim.lr_scheduler.LambdaLR(optimiser, factor)
    start_epoch, best, history = 0, math.inf, []
    if checkpoint.exists():
        state = torch.load(checkpoint, map_location=device, weights_only=False)
        model.load_state_dict(state["model"])
        optimiser.load_state_dict(state["optimiser"])
        scheduler.load_state_dict(state["scheduler"])
        start_epoch, best, history = state["epoch"] + 1, state["best"], state["history"]
        rng.setstate(state["rng"])
        log(f"resumed after epoch {start_epoch}")

    pool = ThreadPoolExecutor(max_workers=max(1, cfg.workers))

    def batch_of(items: Sequence[tuple[Path, Sample]], augmenting: bool) -> tuple[Any, list[Any]]:
        seeds = [rng.randrange(1 << 30) if augmenting else None for _ in items]
        made = list(
            pool.map(
                lambda x: example(
                    x[0][0],
                    x[0][1],
                    cfg.size,
                    None if x[1] is None else random.Random(x[1]),  # noqa: S311
                ),
                zip(items, seeds, strict=True),
            )
        )
        pixels = [p for p, _ in made]
        targets = [{k: v.to(device) for k, v in t.items()} for _, t in made]
        return torch.from_numpy(np.stack(pixels)).to(device), targets

    use_amp = cfg.amp and device == "cuda"
    scaler = torch.amp.GradScaler("cuda", enabled=use_amp)

    for epoch in range(start_epoch, cfg.epochs):
        model.train()
        started, running = time.perf_counter(), 0.0
        if device == "cuda":
            torch.cuda.reset_peak_memory_stats()
        for step in range(cfg.steps):
            for _ in range(cfg.accumulate):
                items = [
                    rng.choice(by_source[rng.choices(list(mix), weights=list(mix.values()))[0]])
                    for _ in range(cfg.batch)
                ]
                x, y = batch_of(items, augmenting=True)
                with torch.autocast("cuda", dtype=torch.float16, enabled=use_amp):
                    loss = model(pixel_values=x, labels=y).loss / cfg.accumulate
                scaler.scale(loss).backward()
                running += loss.item()
            scaler.unscale_(optimiser)
            torch.nn.utils.clip_grad_norm_(model.parameters(), 0.1)
            scaler.step(optimiser)
            scaler.update()
            optimiser.zero_grad(set_to_none=True)
            scheduler.step()
            if (step + 1) % 100 == 0:
                log(
                    f"epoch {epoch + 1} step {step + 1}/{cfg.steps} loss {running / (step + 1):.3f}"
                )
        model.eval()
        val_loss = 0.0
        with torch.no_grad():
            for k in range(0, len(val_set), cfg.batch):
                x, y = batch_of(val_set[k : k + cfg.batch], augmenting=False)
                val_loss += float(model(pixel_values=x, labels=y).loss) * len(y)
        val_loss /= max(1, len(val_set))
        peak = torch.cuda.max_memory_allocated() / 1e9 if device == "cuda" else 0.0
        history.append(
            {
                "epoch": epoch + 1,
                "train_loss": round(running / cfg.steps, 4),
                "val_loss": round(val_loss, 4),
                "seconds": round(time.perf_counter() - started),
                "peak_gpu_gb": round(peak, 2),
            }
        )
        log(f"epoch {epoch + 1}: {history[-1]}")
        if val_loss < best:
            best = val_loss
            model.save_pretrained(cfg.out / "model-best")
        torch.save(
            {
                "model": model.state_dict(),
                "optimiser": optimiser.state_dict(),
                "scheduler": scheduler.state_dict(),
                "epoch": epoch,
                "best": best,
                "history": history,
                "rng": rng.getstate(),
            },
            checkpoint,
        )
    return finish(cfg, history, {k: len(v) for k, v in by_source.items()}, device)


def finish(
    cfg: TrainConfig, history: list[dict[str, Any]], counts: dict[str, int], device: str
) -> Path:
    """Publish the best epoch: weights + config + manifest at ``cfg.out``."""
    best_dir = cfg.out / "model-best"
    for f in best_dir.iterdir():
        (cfg.out / f.name).write_bytes(f.read_bytes())
    weights = next(
        cfg.out / n for n in ("model.safetensors", "pytorch_model.bin") if (cfg.out / n).exists()
    )
    manifest = {
        "name": "shape-detector",
        "version": cfg.version,
        "classes": list(CLASSES),
        "size": cfg.size,
        "base_model": cfg.base,
        "training_images": counts,
        "mix": cfg.weights,
        "config": {
            k: (str(v) if isinstance(v, Path) else v)
            for k, v in asdict(cfg).items()
            if k not in ("manifests", "out", "cache_dir")
        },
        "history": history,
        "device": device,
        "licences": LICENCES,
        "weights_sha256": hashlib.sha256(weights.read_bytes()).hexdigest(),
    }
    (cfg.out / MANIFEST).write_text(json.dumps(manifest, indent=2) + "\n")
    return cfg.out
