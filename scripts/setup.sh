#!/usr/bin/env bash
# scripts/setup.sh — one-command first-time (and idempotent re-run) setup for
# the Docker stack: .env, secrets, NTFS workaround, Postgres/MinIO, migrations,
# seed-if-empty, then api + worker.
#
# Usage:  ./scripts/setup.sh        (or `make setup`)
#
# Safe to re-run: it never overwrites an existing .env value or override file,
# and it seeds ONLY an empty database (reset_and_seed_db.sh TRUNCATES every
# table, so it must never fire against data you've built up).
set -euo pipefail
cd "$(dirname "$0")/.."

say() { printf '\n\033[1m==> %s\033[0m\n' "$*"; }
die() { printf 'error: %s\n' "$*" >&2; exit 1; }

command -v docker  >/dev/null || die "docker is not installed"
docker compose version >/dev/null 2>&1 || die "Docker Compose v2 is required ('docker compose', not 'docker-compose')"
command -v openssl >/dev/null || die "openssl is required to generate secrets"

# ── 1. .env ────────────────────────────────────────────────────────────────
say ".env"
if [[ ! -f .env ]]; then
  cp .env.example .env
  echo "created .env from .env.example"
else
  echo ".env already exists — keeping it"
fi

# Fill a KEY only when its line is exactly `KEY=` (empty). Values you have
# already set are never touched. Hex output is sed/shell/URL safe.
set_if_empty() {
  local key=$1 value=$2
  if grep -qE "^${key}=$" .env; then
    sed -i "s|^${key}=\$|${key}=${value}|" .env
    echo "generated ${key}"
  fi
}
APP_PW=$(openssl rand -hex 24)
set_if_empty APP_DB_PASSWORD  "$APP_PW"
set_if_empty PGPASSWORD       "$APP_PW"   # host-side CLI login = the app role
set_if_empty PGADMIN_PASSWORD "$(openssl rand -hex 24)"
set_if_empty JWT_SECRET       "$(openssl rand -hex 32)"
# GROQ_API_KEY is a real third-party credential — cannot be generated.
if grep -qE '^GROQ_API_KEY=(gsk_your_actual_key_here)?$' .env; then
  echo "note: GROQ_API_KEY is unset in .env — LLM features need a real key"
fi

# Compose reads .env for ${VAR} interpolation; load it here for the psql check.
set -a; . ./.env; set +a

# ── 2. NTFS / Windows-mounted filesystems ──────────────────────────────────
# Postgres's initdb needs Unix ownership/permissions that NTFS (fuseblk/ntfs3)
# and WSL's Windows mounts (drvfs/9p) can't provide, so a named volume living
# there crash-loops with "data directory has wrong ownership". Bind-mount the
# data dir on a native filesystem instead, via a machine-local override
# (gitignored; compose auto-loads it).
say "filesystem check"
docker_root=$(docker info -f '{{.DockerRootDir}}' 2>/dev/null || true)
needs_override=false
for dir in . "$docker_root"; do
  [[ -n $dir && -d $dir ]] || continue
  case "$(stat -f -c %T "$dir" 2>/dev/null || true)" in
    fuseblk|ntfs|ntfs3|drvfs|9p|v9fs) needs_override=true ;;
  esac
done
if $needs_override && [[ ! -f docker-compose.override.yml ]]; then
  pgdir="${XDG_DATA_HOME:-$HOME/.local/share}/ai-evaluation-system/pg_data"
  mkdir -p "$pgdir"
  cat > docker-compose.override.yml <<YAML
# Machine-local override — generated by scripts/setup.sh, not committed
# (see .gitignore). NTFS/Windows-mounted storage can't hold a Postgres data
# directory (wrong-ownership crash loop), so bind-mount a native path.
services:
  postgres:
    volumes:
      - ${pgdir}:/var/lib/postgresql/data
YAML
  echo "NTFS/Windows filesystem detected — wrote docker-compose.override.yml (pg_data -> ${pgdir})"
elif [[ -f docker-compose.override.yml ]]; then
  echo "docker-compose.override.yml already present — keeping it"
else
  echo "native filesystem — no override needed"
fi

# ── 3. Postgres + MinIO ────────────────────────────────────────────────────
# --wait blocks until postgres reports healthy (it has a healthcheck) and
# minio is running (it has none, so "running" is the best compose can check).
say "starting postgres + minio"
docker compose up -d --wait postgres minio

# ── 4. Migrations (also builds the app image the first time) ───────────────
say "applying migrations"
docker compose run --rm migrate

# ── 5. Seed — only when the database has no data ───────────────────────────
# `colleges` is the root of the tenant model and the first table the minimal
# seed fills. Migration 003 inserts one placeholder 'legacy' college on every
# database, so it is excluded: zero OTHER rows means "never seeded".
say "seed check"
rows=$(docker compose exec -T postgres sh -c \
  'psql -U "$POSTGRES_USER" -d "$POSTGRES_DB" -tAc "SELECT count(*) FROM colleges WHERE short_code <> '"'"'legacy'"'"'"' | tr -d '[:space:]')
if [[ "$rows" == "0" ]]; then
  echo "database is empty — loading minimal seed"
  docker compose run --rm seed
else
  echo "database already has data (colleges besides 'legacy': ${rows}) — NOT seeding"
fi

# ── 6. api + worker ────────────────────────────────────────────────────────
say "starting api + worker"
docker compose up -d api worker

printf '\nAPI:            http://localhost:8000  (docs at /docs)\n'
printf 'MinIO console:  http://localhost:9001\n'
printf 'Frontend:       make dev\n'
printf 'First admin:    docker compose run --rm api python scripts/bootstrap_platform_admin.py --help\n'
printf 'Logs:           make logs\n'
